def _law(prefix: str, suffix: str = "") -> str:
    """수집 범위 목록(COVERED_LAWS)에서 법령명을 찾아 쓴다. 손으로 쓰면 가운뎃점(ㆍ U+318D) 같은 문자를 틀리기 쉽다."""
